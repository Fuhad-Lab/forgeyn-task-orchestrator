-- V1: Forgeyn Postgres baseline — the consolidated final state of the upstream SQLite
-- migrations V1..V37, translated to PostgreSQL DDL for the Supabase persistence lane.
--
-- Provenance and translation law (Forgeyn Postgres persistence adapter):
--   The authoritative source for this file is the FINAL schema state produced by applying
--   db/migration/sqlite/V1..V37 to an empty SQLite database (dumped from sqlite_master), NOT a
--   hand-summarized re-reading of the migration chain. The translation rules, applied uniformly:
--     * `BLOB` id/reference columns        -> native `uuid` (Exposed's UUIDColumnType binds
--                                            java.util.UUID natively on Postgres).
--     * `randomblob(16)` column DEFAULTs   -> `gen_random_uuid()` (the same 16 random bytes).
--     * canonical UTC timestamps           -> `text` (the canonical 23-char 'yyyy-MM-dd
--                                            HH:mm:ss.SSS' UTC string — the byte-faithful
--                                            equivalent of how UtcTimestampColumnType persists
--                                            Instants on SQLite; lexicographic order is
--                                            chronological order for the fixed-width format,
--                                            and no session-timezone ever participates).
--     * SQLite INTEGER booleans            -> native `boolean` (Exposed binds Kotlin Boolean);
--                                            their redundant `IN (0,1)` CHECKs are dropped.
--     * `INTEGER PRIMARY KEY AUTOINCREMENT`-> `bigint GENERATED BY DEFAULT AS IDENTITY`,
--                                            seeded above 1e12 exactly like V20 (events.seq).
--     * FTS5 virtual tables + sync triggers-> generated `tsvector` columns with GIN indexes
--                                            (word analyzer) and pg_trgm GIN indexes on the
--                                            source text columns (trigram analyzer), queried
--                                            by PostgresSearchEngine. No shadow tables.
--     * the two cycle-check triggers       -> PL/pgSQL BEFORE INSERT/UPDATE trigger functions.
--   `flyway_schema_history` is created by Flyway itself and is deliberately absent here.
--   role_transitions is absent by upstream final state: V29 backfilled it into `events` and
--   dropped the table.
--
-- This file is the whole Postgres schema history: version numbers above V1 in this location
-- continue the chain exactly as the SQLite location does (a schema that has run this baseline is
-- a 4.0-shaped database; future upstream migrations port onto V2+ here).
-- PREREQUISITE: the pg_trgm extension must be available in the target schema's search path
-- (created once by the database operator: CREATE EXTENSION pg_trgm).

-- ============================================================
-- work_items (self-referencing hierarchy; FKs to config_versions added after that table exists)
-- ============================================================
CREATE TABLE "work_items" (
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    parent_id            uuid REFERENCES "work_items"(id),
    title                text NOT NULL,
    description          text,
    summary              text NOT NULL DEFAULT '',
    role                 text DEFAULT 'queue'
                         CHECK (role IS NULL OR role IN ('queue', 'work', 'review', 'blocked', 'terminal')),
    status_label         text,
    previous_role        text CHECK (previous_role IS NULL OR previous_role IN ('queue', 'work', 'review', 'blocked', 'terminal')),
    priority             text NOT NULL DEFAULT 'medium'
                         CHECK (priority IN ('high', 'medium', 'low')),
    complexity           integer,
    requires_verification boolean NOT NULL DEFAULT false,
    depth                integer NOT NULL DEFAULT 0,
    metadata             text,
    tags                 text,
    type                 text,
    properties           text,
    created_at           text NOT NULL,
    modified_at          text NOT NULL,
    role_changed_at      text NOT NULL,
    version              bigint NOT NULL DEFAULT 1,
    claimed_by           text DEFAULT NULL,
    claimed_at           text DEFAULT NULL,
    claim_expires_at     text DEFAULT NULL,
    original_claimed_at  text DEFAULT NULL,
    root_id              uuid,
    lifecycle            text,
    pinned_server_cfg    uuid,
    pinned_root_cfg      uuid,
    pinned_schema_key    text,
    pinned_schema_layer  text CHECK (pinned_schema_layer IS NULL OR pinned_schema_layer IN ('server', 'root')),
    pinned_at            text CHECK (pinned_at IS NULL OR length(pinned_at) = 23),
    claim_assignment_id  uuid,
    blocked_reason       text
                         CHECK (blocked_reason IS NULL OR blocked_reason IN ('awaiting_decision', 'dependency', 'resource', 'manual')),
    blocked_ref          uuid,
    CHECK ((role IS NULL) = (lifecycle IS NOT NULL AND lifecycle = 'none')),
    -- Forgeyn search lane: the word-analyzer vector (FTS5 porter/unicode61 equivalent) computed
    -- from the same three fields the SQLite triggers indexed, maintained by the database itself.
    fts_text             tsvector GENERATED ALWAYS AS (
                             to_tsvector('english', coalesce(title, '') || ' ' || coalesce(summary, '') || ' ' || coalesce(description, ''))
                         ) STORED
);

CREATE INDEX idx_work_items_parent        ON "work_items"(parent_id);
CREATE INDEX idx_work_items_root_id       ON "work_items"(root_id);
CREATE INDEX idx_work_items_role          ON "work_items"(role);
CREATE INDEX idx_work_items_depth         ON "work_items"(depth);
CREATE INDEX idx_work_items_priority      ON "work_items"(priority);
CREATE INDEX idx_work_items_role_changed  ON "work_items"(role, role_changed_at);
CREATE INDEX idx_work_items_claimed_by    ON "work_items"(claimed_by);
CREATE INDEX idx_work_items_claim_expires ON "work_items"(claim_expires_at);

-- Forgeyn search lane: trigram analyzer (FTS5 trigram tokenizer equivalent).
CREATE INDEX idx_work_items_title_trgm    ON "work_items" USING gin (title gin_trgm_ops);
CREATE INDEX idx_work_items_summary_trgm  ON "work_items" USING gin (summary gin_trgm_ops);
CREATE INDEX idx_work_items_descr_trgm    ON "work_items" USING gin (description gin_trgm_ops);
CREATE INDEX idx_work_items_fts_text      ON "work_items" USING gin (fts_text);

