-- ============================================================
-- The parent-cycle guards (V1's two BEFORE triggers, PL/pgSQL form)
-- ============================================================
CREATE OR REPLACE FUNCTION work_items_cycle_check() RETURNS trigger AS $$
BEGIN
    -- Self-reference guard: catches a parent_id equal to the row's own id.
    IF NEW.parent_id = NEW.id THEN
        RAISE EXCEPTION 'cycle detected: parent_id equals id (self-reference)';
    END IF;
    -- Ancestor walk: rejects a parent_id that resolves to a descendant of this item.
    IF EXISTS (
        WITH RECURSIVE ancestors(node_id) AS (
            SELECT parent_id
            FROM   "work_items"
            WHERE  id = NEW.parent_id
              AND  parent_id IS NOT NULL
            UNION ALL
            SELECT wi.parent_id
            FROM   "work_items" wi
            JOIN   ancestors a ON wi.id = a.node_id
            WHERE  wi.parent_id IS NOT NULL
        )
        SELECT 1 FROM ancestors WHERE node_id = NEW.id
    ) THEN
        RAISE EXCEPTION 'cycle detected: parent_id references a descendant of this item';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER work_items_cycle_check
BEFORE INSERT ON "work_items"
FOR EACH ROW WHEN (NEW.parent_id IS NOT NULL)
EXECUTE FUNCTION work_items_cycle_check();

CREATE TRIGGER work_items_cycle_check_update
BEFORE UPDATE OF parent_id ON "work_items"
FOR EACH ROW WHEN (NEW.parent_id IS NOT NULL)
EXECUTE FUNCTION work_items_cycle_check();
